describe('config.rex', function()
  it('defaults to no routing', function()
    local config = require('lazy-url.config')
    local merged = config.merge()
    T.eq({}, merged.rex)
    config.validate(merged)
  end)

  it('accepts a valid rex config', function()
    local lazy = require('lazy-url')
    lazy.setup({ rex = { action = 'lazy_url_open', host = 'kahi-mac-rex' } })
    T.eq({ action = 'lazy_url_open', host = 'kahi-mac-rex' }, lazy.config.rex)
  end)

  it('accepts action without host', function()
    require('lazy-url').setup({ rex = { action = 'lazy_url_open' } })
  end)

  it('rejects a non-string rex.action, naming the field', function()
    T.raises(function()
      require('lazy-url').setup({ rex = { action = 1 } })
    end, 'rex.action')
  end)

  it('rejects an empty rex.host, naming the field', function()
    T.raises(function()
      require('lazy-url').setup({ rex = { action = 'x', host = '' } })
    end, 'rex.host')
  end)

  it('rejects a non-table rex', function()
    T.raises(function()
      require('lazy-url').setup({ rex = 'lazy_url_open' })
    end, 'rex must be a table')
  end)
end)
